import fs from 'node:fs'
import path from 'node:path'

console.log('--- RUNNING TAHAP 8 PWA VALIDATION SUITE ---')

let passed = 0
let failed = 0

function assert(condition, message) {
  if (condition) {
    console.log(`✅ PASS: ${message}`)
    passed++
  } else {
    console.error(`❌ FAIL: ${message}`)
    failed++
  }
}

const rootDir = process.cwd()

// Test 1: Icon existence and size checks in public/
const requiredIcons = [
  'public/favicon.svg',
  'public/apple-touch-icon.png',
  'public/maskable-icon-512x512.png',
  'public/pwa-192x192.png',
  'public/pwa-512x512.png',
]

for (const iconPath of requiredIcons) {
  const fullPath = path.join(rootDir, iconPath)
  const exists = fs.existsSync(fullPath)
  const size = exists ? fs.statSync(fullPath).size : 0
  assert(exists && size > 100, `Icon asset ${iconPath} exists and has valid size (${size} bytes)`)
}

// Test 2: HTML Meta Tags for PWA
const indexHtml = fs.readFileSync(path.join(rootDir, 'index.html'), 'utf-8')
assert(indexHtml.includes('name="theme-color" content="#123B45"'), 'index.html sets theme-color #123B45')
assert(indexHtml.includes('rel="apple-touch-icon" href="/apple-touch-icon.png"'), 'index.html links apple-touch-icon')
assert(indexHtml.includes('name="mobile-web-app-capable" content="yes"'), 'index.html enables mobile-web-app-capable')
assert(indexHtml.includes('viewport-fit=cover'), 'index.html sets viewport-fit=cover for notch devices')

// Test 3: Dist Manifest & Service Worker build verification
const manifestDistPath = path.join(rootDir, 'dist/manifest.webmanifest')
assert(fs.existsSync(manifestDistPath), 'dist/manifest.webmanifest is generated during build')

if (fs.existsSync(manifestDistPath)) {
  const manifest = JSON.parse(fs.readFileSync(manifestDistPath, 'utf-8'))
  assert(manifest.name === 'smartImpact — IoT Water Quality Monitoring', 'Manifest name matches smartImpact specification')
  assert(manifest.short_name === 'smartImpact', 'Manifest short_name matches smartImpact')
  assert(manifest.display === 'standalone', 'Manifest display is standalone')
  assert(manifest.start_url === '/', 'Manifest start_url is /')
  assert(manifest.scope === '/', 'Manifest scope is /')
  assert(manifest.theme_color === '#123B45', 'Manifest theme_color is #123B45')
  assert(manifest.background_color === '#F5F8FA', 'Manifest background_color is #F5F8FA')
  assert(Array.isArray(manifest.icons) && manifest.icons.length >= 3, 'Manifest defines required icon set')

  const has192 = manifest.icons.some((i) => i.sizes === '192x192')
  const has512 = manifest.icons.some((i) => i.sizes === '512x512')
  const hasMaskable = manifest.icons.some((i) => i.purpose === 'maskable')
  assert(has192 && has512 && hasMaskable, 'Manifest includes 192px, 512px, and maskable icons')
}

// Test 4: Service Worker Security and Cache Strategy
const swDistPath = path.join(rootDir, 'dist/sw.js')
assert(fs.existsSync(swDistPath), 'dist/sw.js is generated by Workbox')

if (fs.existsSync(swDistPath)) {
  const swContent = fs.readFileSync(swDistPath, 'utf-8')
  assert(swContent.includes('NetworkOnly'), 'Workbox configures NetworkOnly strategy for /api/ routes (no secrets cached)')
  assert(swContent.includes('cleanupOutdatedCaches'), 'Workbox cleans up outdated caches on new version release')
  assert(swContent.includes('precacheAndRoute'), 'Workbox precaches app shell and UI assets')
}

console.log(`\nRESULTS: ${passed} passed, ${failed} failed.`)
if (failed > 0) process.exit(1)
